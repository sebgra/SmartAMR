"""Generate a demo feature table so the dashboard can be explored offline.

The real pipeline needs the inphared protein FASTA and the BV-BRC proteomes,
several GB of downloads, plus an ESM-C pass over every protein. When those are
not on the machine there is nothing for the dashboard to show.

This module fills that gap **without pretending to be the real thing**:

- the phage accessions, the bacteria names and every **label** are real, read
  from the inphared metadata and the project's own selection files
- the **embeddings are synthetic**: one random centre per host plus noise, so
  the classifiers have a signal to find and the charts have a shape

A ``DEMO_DATA.md`` marker is written beside the table, and the dashboard shows
a banner for as long as it is there. Delete the marker and the table to go
back to real data.
"""

from __future__ import annotations

from pathlib import Path
from typing import List

import numpy as np
import pandas as pd

from SmartAMR.config import Settings

MARKER_NAME = "DEMO_DATA.md"
DEFAULT_DIM = 64
DEFAULT_PHAGES_PER_BACTERIA = 40
DEFAULT_SEED = 42

MARKER_TEXT = """# Demo data

The feature table in this directory was generated by `smartamr demo`.

- Phage accessions, bacteria names and the interaction labels are **real**,
  read from the inphared metadata.
- The embeddings are **synthetic**: one random centre per host plus noise.

So the dashboard works and the pipeline can be exercised end to end, but no
number here is a scientific result. Delete this file and
`features/final_features.csv` to go back to real data.

Rebuild the real table with:

```bash
smartamr embed --kind bacteria
smartamr embed --kind phage
smartamr build-features
```
"""


def marker_path(settings: Settings) -> Path:
    """Where the demo marker lives."""
    return settings.output_dir / MARKER_NAME


def is_demo(settings: Settings) -> bool:
    """True when the current outputs came from :func:`build_demo_features`."""
    return marker_path(settings).exists() and settings.features.exists()


def _selected_phages(settings: Settings, per_bacteria: int, seed: int) -> dict[str, List[str]]:
    """Real accessions per bacteria, from the project's selection file."""
    from SmartAMR.stats import selected_accessions

    selection = selected_accessions(settings.selected_viruses)
    if not selection:
        raise FileNotFoundError(
            f"No phage selection at {settings.selected_viruses}. "
            "Run 'smartamr select-viruses' first."
        )

    rng = np.random.default_rng(seed)
    trimmed: dict[str, List[str]] = {}

    for bacteria, accessions in selection.items():
        unique = sorted(set(accessions))
        if len(unique) > per_bacteria:
            unique = list(rng.choice(unique, size=per_bacteria, replace=False))
        trimmed[bacteria] = unique

    return trimmed


def build_demo_features(
    settings: Settings,
    dim: int = DEFAULT_DIM,
    phages_per_bacteria: int = DEFAULT_PHAGES_PER_BACTERIA,
    seed: int = DEFAULT_SEED,
    separation: float = 1.0,
    confusion_rate: float = 0.35,
) -> Path:
    """Write a demo feature table and its marker, and return the table's path.

    Parameters
    ----------
    settings
        Where to read the selection and write the table.
    dim
        Width of each synthetic embedding; the real ones are far wider.
    phages_per_bacteria
        How many real accessions to keep per bacteria.
    seed
        Random seed.
    separation
        How far apart the per-host centres sit. Lower values make the task
        harder and the metrics less flattering.
    confusion_rate
        Share of phages pulled toward a second host, so the classes overlap.

    Returns
    -------
    pathlib.Path
        The feature table that was written.
    """

    from SmartAMR.data.viruses import read_inphared_metadata
    from SmartAMR.embedding.features import build_features, save_features

    metadata = read_inphared_metadata(settings.inphared_metadata)
    selection = _selected_phages(settings, phages_per_bacteria, seed)

    rng = np.random.default_rng(seed)
    bacteria_names = sorted(selection)

    # One centre per host; a phage sits near the centre of the host it was
    # isolated on, which is the structure the real embeddings are hoped to have.
    centres = {name: rng.normal(0, 1, dim) * separation for name in bacteria_names}

    phage_rows: dict[str, np.ndarray] = {}
    for bacteria, accessions in selection.items():
        for accession in accessions:
            if accession in phage_rows:
                continue  # a phage isolated on two hosts keeps its first centre

            centre = centres[bacteria]

            # Some phages are pulled toward another host, so the hosts overlap
            # instead of separating perfectly. Without this the demo scores
            # 100% on every task and the confusion matrices say nothing.
            if rng.random() < confusion_rate and len(bacteria_names) > 1:
                others = [name for name in bacteria_names if name != bacteria]
                pull = rng.uniform(0.35, 0.65)
                centre = (1 - pull) * centre + pull * centres[rng.choice(others)]

            phage_rows[accession] = centre + rng.normal(0, 1, dim)

    phage_embeddings = pd.DataFrame(
        {"phage_id": list(phage_rows), "embeddings": list(phage_rows.values())}
    )
    bacteria_embeddings = pd.DataFrame(
        {
            "bacteria_id": bacteria_names,
            "embeddings": [centres[name] + rng.normal(0, 0.3, dim) for name in bacteria_names],
        }
    )

    # The labels come from the real metadata, exactly as in the notebook.
    features = build_features(phage_embeddings, bacteria_embeddings, metadata)

    settings.ensure(settings.output_dir)
    path = save_features(features, settings.features)
    marker_path(settings).write_text(MARKER_TEXT, encoding="utf-8")

    positives = int(features["label"].sum())
    print(
        f"Demo table: {len(features):,} pairs "
        f"({positives:,} interacting), {len(phage_embeddings):,} phages, "
        f"{len(bacteria_names)} bacteria, {dim}-dimensional synthetic embeddings"
    )

    return path


def clear_demo(settings: Settings) -> List[Path]:
    """Remove the demo table and its marker. Returns what was deleted."""
    removed: List[Path] = []

    for path in (settings.features, marker_path(settings)):
        if path.exists():
            path.unlink()
            removed.append(path)

    return removed
